function normalizeArea(value) {
  const v = value.trim().replace(/\s+/g, ' ');
  if (!v) return 'غير محدد';
  if (/المعلمين/.test(v)) return 'حي المعلمين';
  if (/طهمازي/.test(v)) return 'الطهمازية';
  if (/اكرمين/.test(v)) return 'الأكرمين';
  return v;
}

function parseRow(line) {
  const [name, rawAddress] = line.split('\t');
  const parts = rawAddress.split('/').map(x => x.trim());
  const phone = parts.at(-1) || '';
  const landmark = parts.at(-2) || 'غير محدد';
  return {
    name, rawAddress, phone, landmark,
    governorate: 'بابل', district: parts[0] || 'غير محدد',
    area: normalizeArea(parts[1] || ''),
    mahalla: parts[2] || '', alley: parts[3] || '', house: parts.slice(4, -2).join('/') || '',
  };
}

